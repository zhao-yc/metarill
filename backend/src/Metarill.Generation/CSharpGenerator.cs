public sealed record GenerationResult(IReadOnlyList<string> GeneratedFiles, IReadOnlyList<string> CreatedHandwrittenFiles, string MetadataSha256)
{
    public IReadOnlyList<string> Warnings { get; init; } = [];
}
internal sealed record OwnedFile(string Path, string Sha256);
internal sealed record GenerationManifest(int Version, string ProjectId, string RootNamespace, string MetadataSha256, IReadOnlyList<OwnedFile> Files);
internal sealed record PlannedFile(string Path, string Content, bool Handwritten = false);

/// <summary>先验证完整批次，再写入带摘要的生成归属；不连接业务数据库。</summary>
public sealed class CSharpGenerator
{
    internal const string Header = "// <auto-generated>由 Metarill 元数据生成，请修改元数据或模板。</auto-generated>\n#nullable enable\n";
    private const string ManifestName = ".metarill-generation.json";
    private static readonly JsonSerializerOptions JsonOptions = new(JsonSerializerDefaults.Web) { WriteIndented = true, NewLine = "\n" };

    /// <summary>生成强类型 CRUD 与 uni-app 页面，保护已有手写文件。</summary>
    public GenerationResult Generate(MetadataCatalog catalog, string outputDirectory, string rootNamespace)
    {
        ArgumentNullException.ThrowIfNull(catalog);
        // 生成任务固定自己的元数据快照，避免调用方后续修改混入同一批次。
        catalog = JsonSerializer.Deserialize<MetadataCatalog>(JsonSerializer.Serialize(catalog, JsonOptions), JsonOptions)!;
        ValidateNamespace(rootNamespace);
        MetadataValidation.Validate(catalog);
        var model = GenerationModel.Create(catalog, rootNamespace);
        var files = BackendRenderer.Render(model).Concat(UniappRenderer.Render(model)).Concat(WriteSchemaRenderer.Render(model)).Select(file => file with { Content = file.Content.Replace("\r\n", "\n").Replace("\r", "\n") }).OrderBy(x => x.Path, StringComparer.Ordinal).ToArray();
        if (files.Select(x => x.Path).Distinct(StringComparer.OrdinalIgnoreCase).Count() != files.Length) throw new InvalidOperationException("生成路径存在大小写冲突。");
        var output = Path.GetFullPath(outputDirectory);
        RejectLinks(output);
        foreach (var file in files) SafePath(output, file.Path);
        var hash = Hash(CanonicalMetadata(catalog));
        Directory.CreateDirectory(output);
        using var batchLock = new FileStream(Path.Combine(output, ".metarill-generation.lock"), FileMode.OpenOrCreate, FileAccess.ReadWrite, FileShare.None, 1, FileOptions.DeleteOnClose);
        var manifestPath = SafePath(output, ManifestName);
        var previous = File.Exists(manifestPath) ? JsonSerializer.Deserialize<GenerationManifest>(File.ReadAllText(manifestPath), JsonOptions) : null;
        if (previous is not null && (previous.Version != 1 || previous.ProjectId != catalog.YzProjectId || previous.RootNamespace != rootNamespace))
            throw new InvalidOperationException("输出目录属于其他项目、命名空间或生成协议版本。");
        var owned = (previous?.Files ?? []).ToDictionary(x => x.Path, StringComparer.OrdinalIgnoreCase);
        foreach (var item in owned.Values)
        {
            var path = SafePath(output, item.Path);
            if (File.Exists(path) && Hash(File.ReadAllBytes(path)) != item.Sha256)
                throw new InvalidOperationException($"已生成文件被手动修改，批次未执行：{item.Path}");
        }
        foreach (var file in files.Where(x => !x.Handwritten))
            if (File.Exists(SafePath(output, file.Path)) && !owned.ContainsKey(file.Path))
                throw new InvalidOperationException($"路径已有非归属文件，批次未执行：{file.Path}");
        var generated = files.Where(x => !x.Handwritten).ToArray();
        var firstHandwritten = files.Where(x => x.Handwritten && !File.Exists(SafePath(output, x.Path))).ToArray();
        var currentPaths = generated.Select(x => x.Path).ToHashSet(StringComparer.OrdinalIgnoreCase);
        var stale = owned.Values.Where(x => !currentPaths.Contains(x.Path)).ToArray();
        var manifest = new GenerationManifest(1, catalog.YzProjectId, rootNamespace, hash, generated.Select(x => new OwnedFile(x.Path, Hash(Encoding.UTF8.GetBytes(x.Content)))).ToArray());
        var writes = generated.Concat(firstHandwritten).Append(new PlannedFile(ManifestName, JsonSerializer.Serialize(manifest, JsonOptions) + "\n")).ToArray();
        var originals = writes.Select(x => x.Path).Concat(stale.Select(x => x.Path)).Distinct(StringComparer.OrdinalIgnoreCase)
            .ToDictionary(x => x, x => File.Exists(SafePath(output, x)) ? File.ReadAllBytes(SafePath(output, x)) : null, StringComparer.OrdinalIgnoreCase);
        try
        {
            foreach (var file in writes)
            {
                var path = SafePath(output, file.Path);
                Directory.CreateDirectory(Path.GetDirectoryName(path)!);
                AtomicWrite(path, Encoding.UTF8.GetBytes(file.Content));
            }
            foreach (var file in stale) File.Delete(SafePath(output, file.Path));
        }
        catch
        {
            // 回滚本批次已触碰的文件；旧归属清单在失败后仍可用于再次生成。
            foreach (var (relative, bytes) in originals)
            {
                var path = SafePath(output, relative);
                if (bytes is null) File.Delete(path); else AtomicWrite(path, bytes);
            }
            throw;
        }
        var warnings = model.Tables.SelectMany(table => table.Pages.SelectMany(page => page.DetailColumns.Select(column => (Page: page, Column: column, Result: ControlRenderer.Render(model, table, page, column))))).Where(item => item.Result.UnsupportedReason is not null).Select(item => $"页面 {item.Page.Source.Id} 字段 {item.Column.Source.ColumnName}：{item.Result.UnsupportedReason}").ToArray();
        return new GenerationResult(generated.Select(x => x.Path).ToArray(), firstHandwritten.Select(x => x.Path).ToArray(), hash) { Warnings = warnings };
    }

    /// <summary>拒绝绝对路径、上级目录及符号链接，避免输出越过归属目录。</summary>
    internal static string SafePath(string root, string relative)
    {
        if (Path.IsPathRooted(relative) || relative.Split('/', '\\').Any(x => x is ".." or "." or "")) throw new InvalidOperationException("生成相对路径无效。");
        var full = Path.GetFullPath(Path.Combine(root, relative));
        if (!full.StartsWith(root.TrimEnd(Path.DirectorySeparatorChar) + Path.DirectorySeparatorChar, StringComparison.OrdinalIgnoreCase)) throw new InvalidOperationException("生成路径越界。");
        RejectLinks(full);
        return full;
    }
    /// <summary>拒绝路径中任意现存符号链接或目录联接。</summary>
    private static void RejectLinks(string path)
    {
        for (var current = path; current is not null; current = Path.GetDirectoryName(current))
            if ((File.Exists(current) || Directory.Exists(current)) && (File.GetAttributes(current) & FileAttributes.ReparsePoint) != 0)
                throw new InvalidOperationException("生成目录不能经过符号链接或目录联接。");
    }
    /// <summary>使用同目录临时文件原子替换单个产物。</summary>
    private static void AtomicWrite(string path, byte[] bytes)
    {
        var temporary = path + ".metarill-tmp-" + Guid.NewGuid().ToString("N");
        try { File.WriteAllBytes(temporary, bytes); File.Move(temporary, path, true); }
        finally { if (File.Exists(temporary)) File.Delete(temporary); }
    }
    /// <summary>在渲染前拒绝无效或保留关键字命名空间。</summary>
    private static void ValidateNamespace(string value)
    {
        if (!Regex.IsMatch(value, "^[A-Za-z_][A-Za-z0-9_]*(\\.[A-Za-z_][A-Za-z0-9_]*)*$") || value.Split('.').Any(x => Keywords.Contains(x)))
            throw new InvalidOperationException("C# 根命名空间无效。");
    }
    private static readonly HashSet<string> Keywords = ["class", "namespace", "public", "private", "internal", "void", "string", "int", "long", "event", "base", "this", "new", "return", "using", "default", "object", "dynamic", "record", "struct", "interface", "enum", "delegate", "bool", "decimal", "double", "float", "short", "byte", "char", "null", "true", "false", "var", "params", "ref", "out", "in", "is", "as", "switch", "case", "operator", "readonly", "static", "sealed", "abstract", "protected", "override", "virtual", "partial", "async", "await", "try", "catch", "finally", "throw", "if", "else", "for", "foreach", "while", "do", "break", "continue", "get", "set", "value", "required", "init"];
    /// <summary>按稳定次序编码元数据以计算归属摘要。</summary>
    private static byte[] CanonicalMetadata(MetadataCatalog catalog)
    {
        using var document = JsonDocument.Parse(JsonSerializer.Serialize(catalog, JsonOptions));
        using var stream = new MemoryStream();
        using (var writer = new Utf8JsonWriter(stream)) WriteCanonical(document.RootElement, writer);
        return stream.ToArray();
    }
    /// <summary>对对象键及有标识的记录数组稳定排序。</summary>
    private static void WriteCanonical(JsonElement value, Utf8JsonWriter writer)
    {
        if (value.ValueKind == JsonValueKind.Object)
        {
            writer.WriteStartObject();
            foreach (var item in value.EnumerateObject().OrderBy(x => x.Name, StringComparer.Ordinal)) { writer.WritePropertyName(item.Name); WriteCanonical(item.Value, writer); }
            writer.WriteEndObject();
        }
        else if (value.ValueKind == JsonValueKind.Array)
        {
            writer.WriteStartArray();
            var items = value.EnumerateArray().ToArray();
            if (items.Length != 0 && items.All(x => x.ValueKind == JsonValueKind.Object && x.TryGetProperty("id", out _))) items = items.OrderBy(x => x.GetProperty("id").ToString(), StringComparer.Ordinal).ToArray();
            foreach (var item in items) WriteCanonical(item, writer);
            writer.WriteEndArray();
        }
        else value.WriteTo(writer);
    }
    /// <summary>计算不可逆的生成文件摘要。</summary>
    private static string Hash(byte[] bytes) => Convert.ToHexStringLower(SHA256.HashData(bytes));
}

internal sealed record ColumnModel(ColumnMetadata Source, string Property, string JsonName, string Type)
{
    public bool IsId => Source.ColumnName == "id"; public bool IsJsonArray => Type == "string?" && Source.ControlKind is "FileLibrary" or "MultiCheckBoxDatabase" or "MultiSelectPage"; public string BoundaryType => IsJsonArray ? "JsonElement?" : Type;
    public bool IsSystem => Source.ColumnName is "id" or "delete_no" or "insert_time" or "update_time" or "insert_manager_id" or "update_manager_id" or "insert_manager_name" or "update_manager_name" or "insert_manager_real_name" or "update_manager_real_name" or "insert_user_name" or "update_user_name" or "yz_project_id" or "yz_project_name";
}
internal sealed record PageModel(PageMetadata Source, string Name, IReadOnlyList<ColumnModel> Readable, IReadOnlyList<ColumnModel> Writable, IReadOnlyList<ColumnModel> Searchable, IReadOnlyList<ColumnModel> Sortable, IReadOnlyList<(ColumnModel Column, string Source)> Scopes, IReadOnlyList<ColumnModel> ListColumns, IReadOnlyList<ColumnModel> DetailColumns);
internal sealed record TableModel(TableMetadata Source, string Name, IReadOnlyList<ColumnModel> Columns, IReadOnlyList<PageModel> Pages) { public bool IsGlobal => Source.Extra.TryGetValue("scopeKind", out var scope) && scope.ToString() == "global"; }
internal sealed record GenerationModel(MetadataCatalog Catalog, string Namespace, IReadOnlyList<TableModel> Tables)
{
    /// <summary>把松散元数据编译为不可变生成模型，批次中禁止静默忽略查询范围。</summary>
    public static GenerationModel Create(MetadataCatalog catalog, string rootNamespace)
    {
        var result = new List<TableModel>();
        foreach (var table in catalog.ConfigTables.OrderBy(x => x.TableName, StringComparer.Ordinal))
        {
            if (table.IsFunctionTable != 0 || table.IsView != 0) throw new InvalidOperationException($"首期生成器尚不支持函数表或视图：{table.TableName}");
            var columns = catalog.ConfigColumns.Where(x => x.ConfigTableId == table.Id && x.IsVirtualColumn == 0).OrderBy(x => x.SortNo).ThenBy(x => x.ColumnName, StringComparer.Ordinal)
                .Select(x => new ColumnModel(x, Pascal(x.ColumnName), Camel(x.ColumnName), TypeFor(x))).ToArray();
            if (columns.Count(x => x.IsId && x.Type == "long") != 1) throw new InvalidOperationException($"表 {table.TableName} 必须声明 long 类型 id 主键。");
            if (columns.Select(x => x.Property).Distinct(StringComparer.OrdinalIgnoreCase).Count() != columns.Length) throw new InvalidOperationException("字段在 C# 命名转换后冲突。");
            var pageModels = new List<PageModel>();
            foreach (var page in catalog.ConfigPages.Where(x => x.ConfigTableId == table.Id).OrderBy(x => x.Id, StringComparer.Ordinal))
            {
                if (!Regex.IsMatch(page.Id, "^[A-Za-z0-9_]+$")) throw new InvalidOperationException("页面标识只支持字母、数字和下划线。");
                var fields = catalog.ConfigPageColumns.Where(x => x.ConfigPageId == page.Id).ToArray();
                if (fields.Select(x => x.ConfigColumnId).Distinct().Count() != fields.Length) throw new InvalidOperationException("页面字段重复。");
                foreach (var field in fields)
                    if (!catalog.ConfigColumns.Any(x => x.Id == field.ConfigColumnId && x.ConfigTableId == table.Id)) throw new InvalidOperationException("页面字段跨表引用无效。");
                bool Has(ColumnModel c, Func<PageColumnMetadata, bool> predicate) => fields.Any(f => f.ConfigColumnId == c.Source.Id && predicate(f));
                var pageColumns = columns.OrderBy(c => fields.FirstOrDefault(f => f.ConfigColumnId == c.Source.Id)?.SortNo ?? int.MaxValue).ThenBy(c => c.Source.ColumnName, StringComparer.Ordinal).ToArray();
                var readable = pageColumns.Where(c => c.IsId || Has(c, f => InGrid(f) || InEdit(f))).ToArray();
                var writable = pageColumns.Where(c => !c.IsSystem && Has(c, f => InEdit(f) && !Enabled(f.Extra, "isReadOnly"))).ToArray();
                var search = columns.Where(c => Has(c, f => Enabled(f.Extra, "isSearch") || Enabled(f.Extra, "isInFilter"))).ToArray();
                var sortable = columns.Where(c => Has(c, f => Enabled(f.Extra, "isSort") || Enabled(c.Source.Extra, "isSort"))).ToArray();
                var scopes = CompileScopes(page.WhereSql, columns);
                ValidateOrderBy(page.OrderBy, columns);
                pageModels.Add(new PageModel(page, Pascal(table.TableName) + "Page" + page.Id, readable, writable, search, sortable, scopes, pageColumns.Where(c => Has(c, InGrid)).ToArray(), pageColumns.Where(c => Has(c, InEdit)).ToArray()));
            }
            result.Add(new TableModel(table, Pascal(table.TableName), columns, pageModels));
        }
        if (result.Select(x => x.Name).Distinct(StringComparer.OrdinalIgnoreCase).Count() != result.Count) throw new InvalidOperationException("表在 C# 命名转换后冲突。");
        return new GenerationModel(catalog, rootNamespace, result);
    }
    /// <summary>只编译明确的身份或父记录范围。</summary>
    internal static IReadOnlyList<(ColumnModel Column, string Source)> CompileScopes(string sql, IReadOnlyList<ColumnModel> columns)
    {
        if (string.IsNullOrWhiteSpace(sql)) return [];
        var scopes = new List<(ColumnModel, string)>();
        foreach (var clause in Regex.Split(sql.Trim(), @"\s+AND\s+", RegexOptions.IgnoreCase))
        {
            var match = Regex.Match(clause.Trim(), @"^`?([a-zA-Z_][a-zA-Z0-9_]*)`?\s*=\s*@(current_yz_project_id|parent_id|parentId)$", RegexOptions.IgnoreCase);
            if (!match.Success) throw new InvalidOperationException("WhereSql 尚未获得安全的结构化支持，拒绝生成：" + sql);
            var column = columns.SingleOrDefault(x => x.Source.ColumnName == match.Groups[1].Value.ToLowerInvariant()) ?? throw new InvalidOperationException("查询范围字段不存在。");
            var source = match.Groups[2].Value.Equals("current_yz_project_id", StringComparison.OrdinalIgnoreCase) ? "project" : "parent";
            if ((column.Source.ColumnName == "yz_project_id") != (source == "project")) throw new InvalidOperationException("项目范围必须绑定真实身份。");
            scopes.Add((column, source));
        }
        return scopes;
    }
    /// <summary>默认排序仅允许已声明列和明确方向。</summary>
    internal static IReadOnlyList<(ColumnModel Column, bool Descending)> ValidateOrderBy(string order, IReadOnlyList<ColumnModel> columns)
    {
        if (string.IsNullOrWhiteSpace(order)) return [];
        var result = new List<(ColumnModel, bool)>();
        foreach (var part in order.Split(','))
        {
            var match = Regex.Match(part.Trim(), @"^`?([a-zA-Z_][a-zA-Z0-9_]*)`?(?:\s+(asc|desc))?$", RegexOptions.IgnoreCase);
            var column = match.Success ? columns.SingleOrDefault(x => x.Source.ColumnName == match.Groups[1].Value || x.JsonName == match.Groups[1].Value) : null;
            if (column is null) throw new InvalidOperationException("默认排序只支持明确的列和排序方向。");
            result.Add((column, match.Groups[2].Value.Equals("desc", StringComparison.OrdinalIgnoreCase)));
        }
        return result;
    }    private static bool InGrid(PageColumnMetadata field) => field.Extra.ContainsKey("isInGrid") ? Enabled(field.Extra, "isInGrid") : field.IsShow == 1;
    /// <summary>兼容原平台编辑可见标志。</summary>
    /// <summary>兼容元数据数字或布尔开关。</summary>
    private static bool InEdit(PageColumnMetadata field) => field.Extra.ContainsKey("isInEdit") ? Enabled(field.Extra, "isInEdit") : field.IsEdit == 1;
    /// <summary>兼容元数据数字或布尔开关。</summary>
    internal static bool Enabled(Dictionary<string, JsonElement> extra, string key) => extra.TryGetValue(key, out var value) && (value.ValueKind == JsonValueKind.True || value.ToString() == "1");
    /// <summary>把数据库名称转换为稳定的类型成员名称。</summary>
    internal static string Pascal(string value) => string.Concat(value.Split('_', StringSplitOptions.RemoveEmptyEntries).Select(x => char.ToUpperInvariant(x[0]) + x[1..]));
    /// <summary>把数据库名称转换为稳定的类型成员名称。</summary>
    /// <summary>保留现有前端使用的驼峰 JSON 名称。</summary>
    internal static string Camel(string value) { var name = Pascal(value); return char.ToLowerInvariant(name[0]) + name[1..]; }
    /// <summary>将逻辑数据类型映射为 C# 类型。</summary>
    private static string TypeFor(ColumnMetadata column)
    {
        if (column.ColumnName == "id") { if (column.LogicalType.ToLowerInvariant() is not "id" and not "long" and not "bigint" and not "int64") throw new InvalidOperationException("id 主键必须声明为 64 位整数。"); return "long"; }
        return column.LogicalType.ToLowerInvariant() switch
        {
            "id" or "long" or "bigint" or "int64" => "long?",
            "integer" or "int" or "int32" => "int?",
            "boolean" or "bool" => "bool?",
            "decimal" or "money" or "number" => "decimal?",
            "double" => "double?",
            "date" or "datetime" or "timestamp" => "DateTime?",
            "string" or "text" or "json" or "varchar" => "string?",
            _ => throw new InvalidOperationException($"未知逻辑类型：{column.LogicalType}")
        };
    }
}
